export type ArticleSection =
  | { kind: 'p'; text: string }
  | { kind: 'h2'; text: string }
  | { kind: 'h3'; text: string }
  | { kind: 'quote'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'callout'; title: string; text: string }
  /**
   * 可以帶走的檢查清單。與 list 的差別是每一項有兩層：項目名稱，以及該怎麼做／該問什麼。
   * 買方視角的文章需要這個顆粒度 —— list 只有一層，會把判準壓成一句話，讀者拿不走。
   */
  | {
      kind: 'checklist';
      items: { label: string; detail: string; watch?: string }[];
    }
  /**
   * 兩個選項的逐維度對照。桌機出表格、手機拆成一列一張卡 ——
   * 390px 放不下三欄表格，硬塞會讓整篇文章橫向捲動。
   */
  | {
      kind: 'compare';
      columns: [string, string];
      rows: { label: string; a: string; b: string }[];
    };

/**
 * 文章封面圖示。
 * 介面不放 emoji，新文章一律用這裡對應的 SVG 圖示（對應表在 components/ArticleCard.tsx）。
 */
export type ArticleCoverIcon = 'checklist' | 'cost' | 'reservation' | 'loyalty';

export type Article = {
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  publishedAt: string;
  readingMinutes: number;
  author: { name: string; role: string };
  /**
   * emoji 是既有文章的封面寫法，保留是為了不動已發佈的三篇；
   * 新文章改用 icon（SVG）。兩個都給時以 icon 優先。
   */
  cover: { tone: 'brand' | 'ink' | 'mint'; emoji?: string; icon?: ArticleCoverIcon };
  /**
   * 文末導向對應能力頁的出口。
   *
   * 為什麼不共用作者區塊那顆按鈕：那顆固定指向 /contact，回答的是「要不要聯絡我們」；
   * 這顆回答的是「這個題目的下一頁在哪」。讀者讀完一篇買方視角的文章，
   * 下一步通常不是留資料，是去看那件事實際長什麼樣。沒有給就只留作者區塊那一顆。
   */
  cta?: { heading: string; text: string; label: string; href: string };
  sections: ArticleSection[];
};

